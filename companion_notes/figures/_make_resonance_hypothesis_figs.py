def fig_sum_alignment():
    """lambda_max of the SUMMED operator as every well is truncated together.

    The point of the figure is the coherent-tail case. A direction can be
    individually negligible in every single well -- the smallest singular
    direction of each B_k -- and still dominate lambda_max of the sum, if
    the 40 factors all place it in the same place. Truncation removes that
    direction from all 40 at once, so the collective mode disappears even
    though each well barely changed.

    Synthetic, shaped like the deployed configuration: d = 384,
    K = 8 wells x n_c = 5 channels = 40 rank-4 factors.
    """
    rng = np.random.default_rng(7)
    d, n_fac, r = 384, 40, 4
    shared = rng.standard_normal(d)
    shared /= np.linalg.norm(shared)
    c_tail = 0.35                       # individually the SMALLEST column

    def lam_max(rank, coherent):
        tot = np.zeros((d, d))
        for _ in range(n_fac):
            B = rng.standard_normal((d, r)) / np.sqrt(d)
            if coherent:
                B[:, -1] = c_tail * shared
            U, S, Vt = np.linalg.svd(B, full_matrices=False)
            S = S.copy()
            S[rank:] = 0.0
            Bt = U @ np.diag(S) @ Vt
            tot += Bt @ Bt.T
        return np.linalg.eigvalsh(tot)[-1]

    ranks = [4, 3, 2, 1]
    rng = np.random.default_rng(7)
    indep = np.array([lam_max(k, False) for k in ranks])
    rng = np.random.default_rng(7)
    coh = np.array([lam_max(k, True) for k in ranks])
    indep_n, coh_n = indep / indep[0], coh / coh[0]

    fig, ax = plt.subplots(figsize=(8.4, 4.9))
    xs = np.arange(len(ranks))
    ax.plot(xs, coh_n, "o-", color=PURPLE, lw=2.4, ms=9,
            label="coherent tail (same weak direction in every well)")
    ax.plot(xs, indep_n, "s--", color=GREY, lw=2.0, ms=8,
            label="independent wells")

    wall = 0.5 * (coh_n[0] + coh_n[1])           # between rank 4 and rank 3
    ax.axhspan(wall, 1.15, color=RED, alpha=0.10)
    ax.axhline(wall, color=RED, ls="--", lw=1.8)
    ax.text(2.92, wall + 0.02, r"$\omega\Delta t = 2$", color=RED,
            fontsize=10.5, fontweight="bold", ha="right")
    ax.text(2.92, 1.08, "amplifying", color="#B91C1C", fontsize=10,
            fontweight="bold", ha="right")

    ax.annotate(f"{100 * (1 - coh_n[1]):.0f}% drop from removing\n"
                "the weakest direction alone",
                xy=(1.0, coh_n[1]), xytext=(1.25, 0.72), fontsize=9.2,
                color=DARK,
                arrowprops=dict(arrowstyle="->", color=PURPLE, lw=1.8))

    ax.set_xticks(xs)
    ax.set_xticklabels([f"rank {k}" for k in ranks])
    ax.set_xlabel("every well truncated to")
    ax.set_ylabel(r"$\lambda_{\max}(L)$, relative to untruncated")
    ax.set_title("A direction too weak to matter in any one well can still\n"
                 "dominate the summed operator")
    ax.legend(fontsize=9.0, loc="lower right")
    ax.set_ylim(0.0, 1.15)
    ax.text(0.02, 0.03,
            "synthetic: $d=384$, 40 rank-4 factors.\nWall position illustrative.",
            transform=ax.transAxes, fontsize=8.3, color=GREY)

    fig.tight_layout()
    fig.savefig("rh_sum_alignment.png", bbox_inches="tight")
    plt.close(fig)
    print(f"coherent tail: lambda_max drops {100 * (1 - coh_n[1]):.0f}% at "
          f"rank 3; independent drops {100 * (1 - indep_n[1]):.0f}%")


