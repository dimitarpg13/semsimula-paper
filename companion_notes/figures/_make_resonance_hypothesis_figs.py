def fig_stability_wall():
    fig, (axA, axB) = plt.subplots(1, 2, figsize=(11.6, 4.3))
    h = np.linspace(0, 3.0, 1200)
    r = rho(h)

    axA.axvspan(0, 2, color=GREEN, alpha=0.10)
    axA.axvspan(2, 3, color=RED, alpha=0.10)
    axA.plot(h, r, color=DARK, lw=2.4)
    axA.axvline(2, color=RED, ls="--", lw=1.8)
    axA.axhline(1, color=GREY, ls=":", lw=1.2)
    axA.text(1.0, 2.2, "stable\n(pure oscillation)", ha="center",
             color="#15803D", fontsize=10, fontweight="bold")
    axA.text(2.55, 2.2, "amplifying", ha="center", color="#B91C1C",
             fontsize=10, fontweight="bold")
    axA.text(2.02, 3.5, r"$\omega\Delta t = 2$", color=RED, fontsize=11,
             fontweight="bold")
    axA.set_xlabel(r"$\omega \Delta t$")
    axA.set_ylabel(r"amplification per kick  $\rho$")
    axA.set_title("A. The wall is a threshold, not a slope")
    axA.set_xlim(0, 3)
    axA.set_ylim(0, 4)

    gain = rho(h) ** N_LAYERS
    axB.axvspan(0, 2, color=GREEN, alpha=0.10)
    axB.axvspan(2, 3, color=RED, alpha=0.10)
    axB.semilogy(h, gain, color=PURPLE, lw=2.4)
    axB.axvline(2, color=RED, ls="--", lw=1.8)

    h_obs = h_for_total_gain(SPIKE_RATIO)
    axB.axhline(SPIKE_RATIO, color=AMBER, ls="--", lw=1.6)
    axB.plot([h_obs], [SPIKE_RATIO], "o", color=AMBER, ms=9,
             markeredgecolor=DARK, zorder=5)
    axB.annotate(
        f"measured spike ratio {SPIKE_RATIO:.0f}x\n"
        rf"$\Rightarrow \omega\Delta t \approx {h_obs:.2f}$"
        f"\n({100 * (h_obs / 2 - 1):.0f}% past the wall)",
        xy=(h_obs, SPIKE_RATIO), xytext=(2.30, 6.0),
        fontsize=9.2, color=DARK,
        arrowprops=dict(arrowstyle="->", color=AMBER, lw=1.8))
    axB.set_xlabel(r"$\omega \Delta t$")
    axB.set_ylabel(rf"total gain through $L={N_LAYERS}$ layers  $\rho^{{{N_LAYERS}}}$")
    axB.set_title("B. Compounding turns a small overshoot into a spike")
    axB.set_xlim(0, 3)
    axB.set_ylim(0.5, 1e5)

    fig.suptitle("Explicit integration of the low-rank channel: an on/off "
                 "instability", fontsize=12.5, fontweight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig("rh_stability_wall.png", bbox_inches="tight")
    plt.close(fig)
    return h_obs


