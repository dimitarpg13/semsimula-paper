def fig_threshold_vs_magnitude():
    fig, (axA, axB) = plt.subplots(1, 2, figsize=(11.6, 4.3))
    rel = np.linspace(-0.10, 0.45, 600)          # relative change in sigma_max^2

    # Magnitude model: gradient proportional to curvature.
    mag = 1.0 + rel
    # Threshold model: baseline until the wall is crossed, then compounding.
    #   omega*dt scales as sqrt(sigma_max^2), baseline placed just under 2.
    base_h = 1.90
    h_of = base_h * np.sqrt(1.0 + rel)
    thr = rho(h_of) ** N_LAYERS

    axA.axvspan(1.0, 24.0, color=BLUE, alpha=0.13)
    axA.text(12.5, 2.2e3, "SS33 measured band\n+1% to +24%", ha="center",
             fontsize=9.2, color="#1D4ED8", fontweight="bold")
    axA.semilogy(100 * rel, mag, color=GREY, lw=2.4,
                 label="magnitude model (gradient $\\propto$ curvature)")
    axA.semilogy(100 * rel, thr, color=PURPLE, lw=2.4,
                 label="threshold model (this note)")
    axA.axhline(1, color=GREY, ls=":", lw=1.2)
    axA.set_xlabel(r"change in $\sigma_{\max}(B_k)^2$  (%)")
    axA.set_ylabel("gradient norm, relative to healthy")
    axA.set_title("A. Same input range, two very different responses")
    axA.legend(fontsize=8.8, loc="lower right")
    axA.set_ylim(0.5, 1e4)

    # Panel B: a pure threshold generates weak correlation.
    #
    # omega*dt is set by lambda_max of the SUMMED operator
    # L = sum_k g_k B_k B_k^T, so any one well's sigma_max^2 is only one of
    # its inputs -- occupancies g_k and cross-well alignment move it at
    # least as much. That is modelled here as `other`, and it is why a
    # deterministic threshold still leaves sigma_max^2 a poor predictor.
    rng = np.random.default_rng(20260913)
    n = 260
    s = rng.normal(1.0, 0.11, n).clip(0.75, 1.45)      # sigma_max^2, relative
    other = rng.normal(1.0, 0.090, n)                   # g_k, alignment
    hh = base_h * np.sqrt(s) * other
    g = rho(hh) ** N_LAYERS * rng.lognormal(0, 0.18, n)
    spiked = g > 5
    axB.scatter(100 * (s[~spiked] - 1), g[~spiked], s=17, color=GREY,
                alpha=0.65, label="ordinary step")
    axB.scatter(100 * (s[spiked] - 1), g[spiked], s=26, color=RED,
                alpha=0.85, label="spike")
    axB.set_yscale("log")
    axB.set_ylim(0.3, 3e7)
    axB.set_xlabel(r"change in $\sigma_{\max}(B_k)^2$  (%)")
    axB.set_ylabel("gradient norm, relative to healthy")
    corr = np.corrcoef(s, np.log(g))[0, 1]
    elev = 100 * (np.median(s[spiked]) / np.median(s[~spiked]) - 1.0)
    axB.set_title(f"B. A deterministic threshold, yet r = {corr:.2f}")
    axB.legend(fontsize=8.8, loc="upper left")
    axB.text(0.97, 0.97,
             f"median $\\sigma_{{\\max}}^2$ at spikes is only "
             f"+{elev:.0f}% higher\n"
             "— the same order SS33 measured (+1% to +24%)",
             transform=axB.transAxes, ha="right", va="top", fontsize=9,
             color=DARK,
             bbox=dict(boxstyle="round,pad=0.4", fc="#FEF3C7", ec=AMBER))
    print(f"panel B: {100 * spiked.mean():.0f}% spiked, r = {corr:.2f}, spike median elevation = +{elev:.1f}%")

    fig.suptitle("Why a threshold mechanism looks like a weak lever under a "
                 "magnitude test", fontsize=12.5, fontweight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig("rh_threshold_vs_magnitude.png", bbox_inches="tight")
    plt.close(fig)


