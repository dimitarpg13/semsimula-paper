GREEN = "#22C55E"
BLUE = "#3B82F6"
RED = "#EF4444"
PURPLE = "#8B5CF6"
GREY = "#9CA3AF"
DARK = "#111827"
AMBER = "#F59E0B"

N_LAYERS = 8

# Measured, step 87196 (A100, 2026-09-13) -- see the note's SS1 table.
ARMS = ["untruncated", "rank 4", "rank 3", "rank 2", "rank 1"]
GRAD = [2539.20, 2539.20, 2.83, 4.35, 2.87]
PPL = [76.6, 76.6, 79.9, 87.2, 105.7]
SPIKE_RATIO = GRAD[0] / GRAD[2]          # ~897x


def rho(h):
    """Exact per-application amplification of leapfrog on a harmonic mode.

    x_{n+1} - (2 - h^2) x_n + x_{n-1} = 0 has roots of modulus 1 while
    h = omega*dt < 2 (pure oscillation, marginally stable) and a real root
    of modulus > 1 beyond it.
    """
    h = np.asarray(h, dtype=float)
    a = 1.0 - h ** 2 / 2.0
    out = np.ones_like(h)
    over = np.abs(a) > 1.0
    aa = np.abs(a[over])
    out[over] = aa + np.sqrt(aa ** 2 - 1.0)
    return out


def h_for_total_gain(gain, n_layers=N_LAYERS):
    """Invert rho(h)^n = gain analytically."""
    r = gain ** (1.0 / n_layers)
    a = (r + 1.0 / r) / 2.0                      # |a|
    return float(np.sqrt(2.0 * (a + 1.0)))       # h from a = h^2/2 - 1


